// Writes app/admin/_modules/registry.generated.ts from the folders in app/admin/_modules/.
// Next has no require.context under Turbopack and a runtime fs scan is not traced into the
// serverless output, so the scan happens here, at predev, prebuild and pretest.
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ID = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/;
const dirs = (path) => readdirSync(path, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name);

// adminDir is app/admin. Folders starting with _ are not modules (_template, _modules itself).
export function generate(adminDir) {
  const modulesDir = join(adminDir, '_modules');
  // A module id equal to a static route folder would never be reached: the static route wins.
  const taken = new Set(dirs(adminDir).filter((d) => !/^[_[(@]/.test(d)));
  const ids = dirs(modulesDir).filter((d) => !d.startsWith('_')).sort();
  const problems = [];
  for (const id of ids) {
    if (!ID.test(id)) problems.push(`${id}: id must be kebab-case (a-z, 0-9, dashes)`);
    if (taken.has(id)) problems.push(`${id}: collides with the static route app/admin/${id}`);
    for (const file of ['manifest.ts', 'page.tsx']) {
      if (!existsSync(join(modulesDir, id, file))) problems.push(`${id}: missing ${file}`);
    }
  }
  if (problems.length) throw new Error(`Admin modules invalid:\n${problems.join('\n')}`);

  const imports = ids.map((id, i) => `import manifest${i} from './${id}/manifest';`);
  const entries = ids.map((id, i) => `  { id: '${id}', manifest: manifest${i}, load: () => import('./${id}/page') },`);
  return [
    '// Generated by scripts/gen-admin-modules.mjs. Do not edit: add a folder and run `npm run gen:admin`.',
    "import type { AdminModule } from './types';",
    ...imports,
    '',
    `export const ADMIN_MODULES: readonly AdminModule[] = [${entries.length ? `\n${entries.join('\n')}\n` : ''}];`,
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const adminDir = join(process.cwd(), 'app/admin');
  writeFileSync(join(adminDir, '_modules/registry.generated.ts'), generate(adminDir));
}
